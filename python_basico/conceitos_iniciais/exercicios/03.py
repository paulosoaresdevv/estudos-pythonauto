# Crie um código onde o usuário deve digitar três notas escolares e calcular a média delas.



fisica = float(input("Digite a nota de fisica: "))
matematica = float(input("Digite a nota de matematica: "))
quimica = float(input("Digite a nota de quimica: "))

resultado = (fisica + matematica + quimica) / 3

print(f"a media das suas notas é: {resultado}")