# Crie um código onde o usuário deve inserir dois números e exiba a soma, subtração, multiplicação e divisão deles.



num01 = int (input ("Digite um número: "))
num02 = int (input ("Digite outro número: "))
adicao = num01 + num02
subtracao = num01 - num02
multiplicacao = num01 * num02
divisao = num01 / num02

print(f"A soma desses dois numeros é igual a {adicao}, a subtração deles é {subtracao}, a multiplacao é {multiplicacao} e a divisao deles é {divisao}")